def fetch_cve(cve_id):
    url = f"https://cveawg.mitre.org/api/cve/{cve_id}"
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    try:
        with urllib.request.urlopen(req, timeout=10) as response:
            data = json.loads(response.read().decode())
            metrics = data.get("containers", {}).get("cna", {}).get("metrics", [])
            
            # ADPs might contain scores too
            adp = data.get("containers", {}).get("adp", [])
            for a in adp:
                if "metrics" in a:
                    metrics.extend(a["metrics"])

            max_score = None
            for m in metrics:
                score = None
                if "cvssV3_1" in m:
                    score = m["cvssV3_1"].get("baseScore")
                elif "cvssV3_0" in m:
                    score = m["cvssV3_0"].get("baseScore")
                elif "cvssV4_0" in m:
                    score = m["cvssV4_0"].get("baseScore")
                elif "cvssV2_0" in m:
                    score = m["cvssV2_0"].get("baseScore")
                
                if score is not None:
                    try:
                        f_score = float(score)
                        if max_score is None or f_score > max_score:
                            max_score = f_score
                    except ValueError:
                        pass
            
            return cve_id, max_score
    except Exception as e:
        return cve_id, f"Error: {e}"

results = []
with concurrent.futures.ThreadPoolExecutor(max_workers=20) as executor:
    future_to_cve = {executor.submit(fetch_cve, cve): cve for cve in cve_list}
    for future in concurrent.futures.as_completed(future_to_cve):
        res = future.result()
        results.append(res)
        print(f"Fetched {res[0]}: {res[1]}")

# Keep the original order
order_dict = {cve: i for i, cve in enumerate(cve_list)}
results.sort(key=lambda x: order_dict[x[0]])

with open("cve_scores.md", "w") as f:
    f.write("| CVE ID | Score |\n")
    f.write("|---|---|\n")
    for cve, score in results:
        f.write(f"| {cve} | {score if score is not None else 'N/A'} |\n")
